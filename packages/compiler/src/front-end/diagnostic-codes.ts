/**
 * MX's diagnostic codes as Mesh's (decision MX-05, ruled 2026-10-14): `MESH_DIALECT.diagnosticCodes`. MX applies the map
 * to every diagnostic `lowerSource` and `checkDialectFile` report on an entity file (since MX 0.1.0-alpha.27), so the
 * build and the editor show the same `MESH_*` code for one mistake. Only the code changes: message, position and
 * severity stay MX's. A code a Mesh hook gives (`ctx.fail(message, { code: "MESH_X" })`) is never renamed.
 *
 * Every code in MX's catalogue (`MX_DIAGNOSTIC_CODES`) has an entry except the four in `MX_KEPT_CODES`, and the type
 * below fails the type check when MX adds a code the map leaves out (`test/diagnostic-codes.test.ts` fails too).
 *
 * The rule: `MX_X` is `MESH_X`, so MX's catalogue still explains a code, with MX's "attribute" (`ATTRIBUTE`, `ATTR`) read
 * as Mesh's "option": in Mesh a `key=value` on a line is an option, and an attribute is an entity's data member
 * (`string :title`). So `MX_UNKNOWN_ATTRIBUTE` is `MESH_UNKNOWN_OPTION`, and an MX attribute tag is an option tag
 * (`MX_UNKNOWN_ATTRIBUTE_TAG` is `MESH_UNKNOWN_OPTION_TAG`). The exceptions carry a note: an MX code whose mistake Mesh
 * already reports under its own code reuses that code (one code per meaning), and an MX word that means something else
 * in Mesh takes Mesh's word.
 */
import type { MxDiagnosticCode } from "@mxlang/core";

/**
 * The codes that stay MX's on a Mesh file. `MX_INTERNAL_ERROR` (a bug in MX) and `MX_DIALECT_HOOK_ERROR` (a Mesh hook
 * that broke MX's contract) cannot be renamed; `MX_DIALECT_ERROR` and `MX_DIALECT_WARNING` (a Mesh hook's error or
 * warning that gave no code) are ignored in a map. Each points at a bug in MX or in Mesh's dialect, not at the file.
 */
